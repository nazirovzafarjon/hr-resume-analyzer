"""Celery background tasks for generating file exports (PDF, XLSX, DOCX).

Workloads are routed to the dedicated ``exports`` queue. Generated files are written
to shared storage volume (UPLOAD_DIR/exports) accessible by the web API and workers.
"""

from __future__ import annotations

import logging
from pathlib import Path
from typing import Any

from celery import Task

from app.core.celery_app import celery_app
from app.core.config import settings
from app.core.database import SessionLocal
from app.schemas.export import ExportFilters
from app.services.export_service import ExportService

logger = logging.getLogger(__name__)


@celery_app.task(
    bind=True,
    name="app.tasks.exports.generate_export_task",
    max_retries=1,
    default_retry_delay=5,
    acks_late=True,
)
def generate_export_task(
    self: Task,
    resource: str,
    filters: dict[str, Any] | None,
    columns: list[str] | None,
    format: str,
    owner_id: int | None = None,
    output_filename: str | None = None,
) -> dict[str, Any]:
    """Generate a table export file in the background.

    Args:
        self: Bound Celery task.
        resource: Target table resource ('applications', 'jobs', 'interviews').
        filters: Column filters to apply.
        columns: List of columns to include.
        format: Export format ('pdf', 'xlsx', 'docx').
        owner_id: HR user ID for data scoping (None for admin).
        output_filename: Optional target filename override.

    Returns:
        dict containing export summary and file metadata.
    """
    logger.info(
        "Celery task generate_export_task[id=%s, resource=%s, format=%s, owner_id=%s]",
        self.request.id,
        resource,
        format,
        owner_id,
    )

    with SessionLocal() as db:
        service = ExportService(db, owner_id)
        try:
            filters_obj: ExportFilters | None = None
            if isinstance(filters, dict):
                filters_obj = ExportFilters(**filters)
            elif isinstance(filters, ExportFilters):
                filters_obj = filters

            file_stream, default_filename, record_count = service.export(
                resource=resource,
                filters=filters_obj,
                columns=columns,
                format=format,
            )

            filename = output_filename or default_filename
            export_dir = Path(settings.UPLOAD_DIR) / "exports"
            export_dir.mkdir(parents=True, exist_ok=True)
            target_path = export_dir / filename

            # Write generated bytes to the shared storage directory
            file_bytes = file_stream.getvalue()
            with open(target_path, "wb") as f:
                f.write(file_bytes)

            logger.info(
                "Export generated successfully: filename=%s, records=%d, size_bytes=%d",
                filename,
                record_count,
                len(file_bytes),
            )

            return {
                "status": "completed",
                "filename": filename,
                "record_count": record_count,
                "file_size": len(file_bytes),
                "format": format,
                "relative_path": f"exports/{filename}",
            }

        except (ValueError, KeyError) as exc:
            logger.warning("Export generation validation error: %s", exc)
            return {
                "status": "invalid_parameters",
                "error": str(exc),
            }
        except Exception as exc:
            logger.exception("Export generation failed: %s", exc)
            return {
                "status": "failed",
                "error": str(exc),
            }
